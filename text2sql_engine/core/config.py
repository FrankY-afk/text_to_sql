"""Configuration and initialization for HuggingFace embeddings, ChromaDB, and LLM backends."""

from __future__ import annotations

import os
from typing import Any, List, Optional
from pydantic import Field
from pydantic_settings import BaseSettings, SettingsConfigDict
import chromadb
from chromadb.config import Settings as ChromaSettings
from langchain_huggingface import HuggingFaceEmbeddings
from langchain_chroma import Chroma
from langchain_core.language_models.chat_models import BaseChatModel
from langchain_core.messages import BaseMessage, AIMessage
from langchain_core.outputs import ChatResult, ChatGeneration


class EngineSettings(BaseSettings):
    """Central configuration for Text-to-SQL Engine."""

    model_config = SettingsConfigDict(env_prefix="TEXT2SQL_", env_file=".env", extra="ignore")

    # Embeddings Configuration (BAAI/bge-small-en-v1.5)
    embedding_model_name: str = Field(default="BAAI/bge-small-en-v1.5", description="Local HuggingFace embedding model")
    embedding_device: str = Field(default="cpu", description="Device for embedding execution ('cpu' or 'cuda')")

    # ChromaDB Configuration
    chroma_db_dir: str = Field(default="./chroma_db", description="Local directory for persistent ChromaDB storage")

    # LLM / SQL Coder Configuration
    llm_model: str = Field(default="Qwen/Qwen2.5-Coder-32B-Instruct", description="Target Qwen coder model name")
    ollama_model: str = Field(default="qwen2.5-coder:7b", description="Local Ollama model tag")
    ollama_base_url: str = Field(default="http://localhost:11434", description="Ollama API base URL")
    hf_api_token: Optional[str] = Field(default=None, description="Optional Hugging Face Hub token")

    # Local Database Engine
    duckdb_path: str = Field(default="./data/warehouse.duckdb", description="Path to DuckDB database file")


_settings: Optional[EngineSettings] = None
_embeddings_instance: Optional[HuggingFaceEmbeddings] = None


def get_settings() -> EngineSettings:
    """Get or initialize singleton engine settings."""
    global _settings
    if _settings is None:
        _settings = EngineSettings()
    return _settings


def get_embeddings() -> HuggingFaceEmbeddings:
    """Return cached HuggingFaceEmbeddings instance running locally."""
    global _embeddings_instance
    if _embeddings_instance is None:
        settings = get_settings()
        _embeddings_instance = HuggingFaceEmbeddings(
            model_name=settings.embedding_model_name,
            model_kwargs={"device": settings.embedding_device},
            encode_kwargs={"normalize_embeddings": True},
        )
    return _embeddings_instance


def get_chroma_client(persist_directory: Optional[str] = None, in_memory: bool = False) -> chromadb.ClientAPI:
    """Initialize ChromaDB client (persistent or in-memory)."""
    settings = get_settings()
    if in_memory:
        return chromadb.EphemeralClient()
    target_dir = persist_directory or settings.chroma_db_dir
    os.makedirs(target_dir, exist_ok=True)
    return chromadb.PersistentClient(path=target_dir)


def get_vector_store(
    collection_name: str,
    persist_directory: Optional[str] = None,
    in_memory: bool = False,
) -> Chroma:
    """Initialize LangChain Chroma vector store with local BAAI embeddings."""
    embeddings = get_embeddings()
    client = get_chroma_client(persist_directory=persist_directory, in_memory=in_memory)
    return Chroma(
        client=client,
        collection_name=collection_name,
        embedding_function=embeddings,
    )


class LocalDeterministicCoder(BaseChatModel):
    """Zero-cost local deterministic SQL coder fallback.
    
    Used when running offline without an active Ollama instance or HuggingFace API key.
    Provides standard AST & dialect-aware synthesis ensuring tests and pipelines
    execute reliably without external services.
    """

    model_name: str = "local-deterministic-qwen-coder"

    def _generate(
        self,
        messages: List[BaseMessage],
        stop: Optional[List[str]] = None,
        run_manager: Optional[Any] = None,
        **kwargs: Any,
    ) -> ChatResult:
        last_message = messages[-1].content if messages else ""
        response_text = f"/* Generated by {self.model_name} */\nSELECT 1;"
        message = AIMessage(content=response_text)
        generation = ChatGeneration(message=message)
        return ChatResult(generations=[generation])

    @property
    def _llm_type(self) -> str:
        return "local_deterministic_coder"


def get_llm(temperature: float = 0.0) -> BaseChatModel:
    """Get LLM backend based on environment availability.
    
    Priority:
    1. Ollama (if reachable at ollama_base_url)
    2. Hugging Face Inference API (if hf_api_token is set)
    3. LocalDeterministicCoder (zero-cost offline fallback)
    """
    settings = get_settings()

    # Try Ollama if configured
    try:
        import urllib.request
        req = urllib.request.Request(f"{settings.ollama_base_url}/api/tags", headers={"User-Agent": "text2sql"})
        with urllib.request.urlopen(req, timeout=1.0) as resp:
            if resp.status == 200:
                from langchain_community.chat_models import ChatOllama
                return ChatOllama(
                    base_url=settings.ollama_base_url,
                    model=settings.ollama_model,
                    temperature=temperature,
                )
    except Exception:
        pass

    # Try HuggingFace if token provided
    token = settings.hf_api_token or os.environ.get("HUGGINGFACEHUB_API_TOKEN") or os.environ.get("HF_TOKEN")
    if token:
        try:
            from langchain_huggingface import ChatHuggingFace, HuggingFaceEndpoint
            endpoint = HuggingFaceEndpoint(
                repo_id=settings.llm_model,
                huggingfacehub_api_token=token,
                temperature=temperature,
            )
            return ChatHuggingFace(llm=endpoint)
        except Exception:
            pass

    # Return local deterministic fallback
    return LocalDeterministicCoder()
